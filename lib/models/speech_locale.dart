/// Display names only; always keep the engine's original locale as its identity.
abstract final class SpeechLocale {
  static String label(String locale) {
    final parts = locale.trim().replaceAll('_', '-').split('-');
    final language = parts.first.toLowerCase();
    if (language.isEmpty) return 'Unknown language';
    final name = _languages[language];
    if (name == null) return 'Language ($locale)';
    final qualifiers = <String>[];
    for (final part in parts.skip(1)) {
      if (part.length == 1) break; // BCP 47 extensions are not regions.
      if (_scripts.containsKey(part.toLowerCase())) {
        qualifiers.add(_scripts[part.toLowerCase()]!);
      } else if (RegExp(r'^[a-zA-Z]{2}$|^\d{3}$').hasMatch(part)) {
        qualifiers.add(_regions[part.toUpperCase()] ?? part.toUpperCase());
      }
    }
    return qualifiers.isEmpty ? name : '$name (${qualifiers.join(', ')})';
  }

